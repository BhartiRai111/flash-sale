package com.bharti.flashsale.order.web;

import java.util.List;
import java.util.UUID;

import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import com.bharti.flashsale.order.service.OrderService;
import com.bharti.flashsale.order.service.OrderService.CreateResult;

import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import lombok.RequiredArgsConstructor;

/**
 * X-User-Id is set by the API gateway after validating the JWT.
 * Idempotency-Key is generated by the client (e.g. a UUID) once per "Buy" click.
 */
@RestController
@RequestMapping("/api/orders")
@RequiredArgsConstructor
public class OrderController {

    private final OrderService orderService;

    @PostMapping
    public ResponseEntity<OrderResponse> create(
            @RequestHeader("X-User-Id") String userId,
            @RequestHeader("Idempotency-Key") @NotBlank @Size(max = 100) String idempotencyKey,
            @Valid @RequestBody CreateOrderRequest request) {
        CreateResult result = orderService.createOrder(userId, idempotencyKey, request);
        // 202: the order is accepted and will be confirmed or cancelled asynchronously by the saga
        HttpStatus status = result.created() ? HttpStatus.ACCEPTED : HttpStatus.OK;
        return ResponseEntity.status(status).body(OrderResponse.from(result.order()));
    }

    @GetMapping("/{orderId}")
    public OrderResponse get(@RequestHeader("X-User-Id") String userId, @PathVariable UUID orderId) {
        return OrderResponse.from(orderService.getOrder(orderId, userId));
    }

    @GetMapping
    public List<OrderResponse> list(@RequestHeader("X-User-Id") String userId) {
        return orderService.getOrders(userId).stream().map(OrderResponse::from).toList();
    }
}
